"""Extract chosen game-icons.net SVG paths (CC BY 3.0) into js/icons.js.
Usage: python3 tools/build_icons.py <path-to-game-icons-repo>"""
import sys, re, pathlib, json
root = pathlib.Path(sys.argv[1])
NAMES = """punch templar-shield sharp-axe bandage-roll whirlwind trumpet
fangs burning-embers fluffy-flame fire-breath fire-gem match-head burning-forest feathered-wing
sewing-needle poison-bottle bee poison-cloud virus scorpion-tail rat leeching-worm snake-tongue
cross-shield spiked-shell shield-impact locked-fortress spiked-armor knight-banner turtle weight tribal-shield
mirror-mirror cog gears bouncing-spring pendulum-swing metronome anticlockwise-rotation clock-tower lightning-arc
coinflip assassin-pocket cash gold-bar coins-pile price-tag slot-machine gems clover gold-shell
carnivore-mouth sacrificial-dagger portal shard-sword magic-portal all-seeing-eye crowned-skull dripping-knife
dust-cloud paper-plane paper-clip centipede stapler-heavy-duty zat-gun box-cutter
slime metal-golem-head butterfly two-shadows floating-ghost mimic-chest octopus old-king
hound cobra raven hanging-spider dragon-head rock-golem spectre
black-knight-helm candle-flame fox-head
two-coins heart-beats poison broken-shield broken-bone thorny-vine biceps flame
crossed-swords horned-skull shop magnifying-glass campfire card-random card-draw padlock star-swirl swap-bag
sparkles hourglass cuckoo-clock bright-explosion treasure-map open-treasure-chest ticket target-arrows locked-chest shopping-bag""".split()
index = {}
for p in root.rglob('*.svg'):
    index.setdefault(p.stem, p)
out = {}
for n in NAMES:
    p = index.get(n)
    if not p: sys.exit(f'missing icon {n}')
    svg = p.read_text()
    ds = [d for d in re.findall(r'<path[^>]*?\sd="([^"]+)"', svg) if d.strip() != 'M0 0h512v512H0z']
    out[n] = ' '.join(ds)
js = '// Icons from game-icons.net (CC BY 3.0) by Lorc, Delapouite & contributors.\n// Generated by tools/build_icons.py - do not edit by hand.\nexport const ICONS = ' + json.dumps(out, separators=(',',':')) + ';\n'
pathlib.Path('js/icons.js').write_text(js)
print(len(out), 'icons,', len(js)//1024, 'KB')
